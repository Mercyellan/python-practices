#simple concepts of integers in python and what each sign does 

a = 40
b = 5

print(a + b)   # Output: 45
print(a - b)   # Output: 35
print(a * b)   # Output: 200
print(a / b)   # Output: 4.0
print(a // b)  # Output: 4
print(a % b)   # Output: 0
print(a ** b)  # Output: 1000

#advance concept of integers 
big_number = 2 ** 1000
print (big_number)

#base conversion 
number = 225

